import 'dart:io';

import 'package:path/path.dart' as p;

import '../../configuration/config_loader.dart';
import '../../configuration/project_detector.dart';
import '../../parsers/translation_catalog.dart';
import 'base_command.dart';

class InitCommand extends L10nSweepCommand {
  InitCommand(super.env) {
    argParser
      ..addFlag(
        'force',
        negatable: false,
        help: 'Overwrite an existing ${ConfigLoader.fileName}.',
      )
      ..addFlag(
        'stdout',
        negatable: false,
        help: 'Print the configuration instead of writing it.',
      );
  }

  @override
  String get name => 'init';

  @override
  String get description =>
      'Create ${ConfigLoader.fileName} from the detected project structure.';

  @override
  int execute() {
    final args = argResults!;
    final root = projectRoot;
    if (!Directory(root).existsSync()) {
      logger.error('Project directory "$root" does not exist.');
      return ExitCode.error;
    }
    final target = File(p.join(root, ConfigLoader.fileName));
    final toStdout = args['stdout'] as bool;
    if (!toStdout && target.existsSync() && !(args['force'] as bool)) {
      logger.error(
        '${ConfigLoader.fileName} already exists. Use --force to overwrite it.',
      );
      return ExitCode.error;
    }

    final detected = const ProjectDetector().detect(root);
    final content = generate(root, detected);
    if (toStdout) {
      logger.write(content);
      return ExitCode.success;
    }
    target.writeAsStringSync(content);
    logger.success('Created ${target.path}');
    if (!detected.hasPubspec) {
      logger.warn('No pubspec.yaml found; is this the project root?');
    }
    if (!detected.hasEasyLocalization) {
      logger.warn('easy_localization is not listed in pubspec.yaml.');
    }
    if (detected.translationsPath == null) {
      logger.warn(
        'No translations directory was found; edit translations_path.',
      );
    }
    logger.info('');
    logger.info('Next steps:');
    logger.info('  dart run l10n_sweep doctor');
    logger.info('  dart run l10n_sweep analyze');
    logger.detail(
      'Tip: add ".l10n_sweep/" (the backup directory) to .gitignore.',
    );
    return ExitCode.success;
  }

  /// Builds the configuration file contents.
  static String generate(String root, DetectedProject detected) {
    final translationsPath = detected.translationsPath ?? 'assets/translations';
    final locales = <String>[];
    final dir = Directory(p.join(root, translationsPath));
    if (dir.existsSync()) {
      for (final f in dir.listSync().whereType<File>()) {
        final locale = TranslationCatalog.localeFromFileName(
          p.basename(f.path),
        );
        if (locale != null) locales.add(locale);
      }
      locales.sort();
    }
    final primary =
        detected.fallbackLocale ??
        (locales.contains('en') ? 'en' : (locales.firstOrNull ?? 'en'));

    final excluded = <String>{
      for (final keysFile in detected.generatedKeysPaths)
        p.posix.dirname(keysFile) == 'lib'
            ? keysFile
            : p.posix.dirname(keysFile),
      '**/*.g.dart',
      '**/*.freezed.dart',
    };

    final buffer = StringBuffer()
      ..writeln('# Configuration for l10n_sweep.')
      ..writeln('# Generated by "dart run l10n_sweep init".')
      ..writeln('l10n_sweep:')
      ..writeln('  # Directory containing <locale>.json files.')
      ..writeln('  translations_path: $translationsPath')
      ..writeln()
      ..writeln(
        '  # Keys are removed based on this locale'
        '${locales.isEmpty ? '' : ' (found: ${locales.join(', ')})'}.',
      )
      ..writeln('  primary_locale: $primary')
      ..writeln()
      ..writeln('  source_paths:')
      ..writeln('    - lib')
      ..writeln()
      ..writeln('  file_extensions:')
      ..writeln('    - dart')
      ..writeln()
      ..writeln(
        '  # Files here are not scanned for translation calls, but '
        'their',
      )
      ..writeln(
        '  # constants (such as generated LocaleKeys) are still '
        'resolved.',
      )
      ..writeln('  excluded_paths:');
    for (final path in excluded) {
      buffer.writeln("    - '$path'");
    }
    buffer
      ..writeln()
      ..writeln(
        '  # Never reported and never removed. Globs with * are '
        'allowed.',
      )
      ..writeln('  excluded_keys: []')
      ..writeln()
      ..writeln('  # Always treated as used.')
      ..writeln('  ignored_keys: []')
      ..writeln()
      ..writeln(
        '  # Keys built at run time that must be kept, '
        "e.g. 'onboarding.step_*'.",
      )
      ..writeln('  dynamic_key_patterns: []')
      ..writeln()
      ..writeln('  # Custom wrappers the analyzer cannot follow, e.g.')
      ..writeln('  #   - name: translate')
      ..writeln('  #     key_argument: 0')
      ..writeln('  translation_functions: []')
      ..writeln()
      ..writeln('  output:')
      ..writeln('    format: console')
      ..writeln('    path: build/l10n_sweep_report.json')
      ..writeln()
      ..writeln('  safety:')
      ..writeln('    create_backup: true')
      ..writeln('    backup_path: .l10n_sweep/backups')
      ..writeln('    require_confirmation: true')
      ..writeln('    preserve_uncertain_keys: true')
      ..writeln(
        '    # Keep false: unresolved translation calls then prevent '
        'keys from',
      )
      ..writeln('    # being classified as definitely unused.')
      ..writeln('    allow_unresolved_references: false')
      ..writeln()
      ..writeln('  cleanup:')
      ..writeln('    remove_empty_parents: true');
    return buffer.toString();
  }
}
